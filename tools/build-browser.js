#!/usr/bin/env node
'use strict';
// Builds browser/schedule.js: @rhylthyme/timeline/schedule as one classic
// script for a <script> tag, with no bundler and no dependencies. It wraps
// src/schedule/browser.js and everything it requires (the engine, the
// instrument modules, the galago catalogue) in a small CommonJS loader and
// sets window.RhylthymeSchedule. Also builds browser/labmcp-catalog.js, the
// LabMCP instrument catalogue (about 350 KB) as a script that registers it
// with window.RhylthymeSchedule, for pages whose programs have LabMCP steps.
// Run by `npm test` and before `npm pack`.

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const ENTRY = 'src/schedule/browser.js';
const OUT = path.join(ROOT, 'browser', 'schedule.js');
const CATALOG = 'src/schedule/labmcp-catalog.json';
const CATALOG_OUT = path.join(ROOT, 'browser', 'labmcp-catalog.js');
const version = require('../package.json').version;

const modules = new Map(); // relative path -> { code, deps: { request: relative path } }

function resolve(from, request) {
  if (!request.startsWith('.')) throw new Error(`${from}: only relative requires can be bundled, not ${request}`);
  const target = path.posix.normalize(path.posix.join(path.posix.dirname(from), request));
  if (!fs.existsSync(path.join(ROOT, target))) throw new Error(`${from}: cannot find ${request}`);
  return target;
}

function add(rel) {
  if (modules.has(rel)) return;
  const code = fs.readFileSync(path.join(ROOT, rel), 'utf8');
  const deps = {};
  modules.set(rel, { code, deps });
  if (rel.endsWith('.json')) return;
  for (const m of code.matchAll(/\brequire\(\s*["']([^"']+)["']\s*\)/g)) {
    deps[m[1]] = resolve(rel, m[1]);
    add(deps[m[1]]);
  }
}

add(ENTRY);
if (modules.has(CATALOG)) throw new Error(`${ENTRY} must not require ${CATALOG}: it ships as browser/labmcp-catalog.js`);

const defs = [...modules].map(([rel, { code, deps }]) => {
  const body = rel.endsWith('.json')
    ? `module.exports = ${JSON.stringify(JSON.parse(code))};`
    : code;
  return `  ${JSON.stringify(rel)}: [function (module, exports, require, define) {\n${body}\n  }, ${JSON.stringify(deps)}]`;
});

const out = `/*! @rhylthyme/timeline ${version} | browser/schedule.js | Apache-2.0
 * The validator and analyzer from @rhylthyme/timeline/schedule as one
 * script: <script src=".../browser/schedule.js"></script> sets
 * window.RhylthymeSchedule. The LabMCP instrument catalogue is not in it:
 * add browser/labmcp-catalog.js (before or after) to check LabMCP steps.
 * Generated by tools/build-browser.js; edit src/.
 */
(function (root) {
  'use strict';
  var defs = {
${defs.join(',\n')}
  };
  var cache = {};
  function load(rel) {
    if (cache[rel]) return cache[rel].exports;
    var module = cache[rel] = { exports: {} };
    var def = defs[rel];
    // define is passed as undefined so the engine's UMD header takes the
    // CommonJS branch even on a page that has an AMD loader.
    def[0].call(module.exports, module, module.exports, function (request) {
      if (!(request in def[1])) throw new Error('browser/schedule.js: ' + rel + ' requires unbundled ' + request);
      return load(def[1][request]);
    }, undefined);
    return module.exports;
  }
  var S = root.RhylthymeSchedule = load(${JSON.stringify(ENTRY)});
  // browser/labmcp-catalog.js ran first: register what it left
  if (root.RhylthymeLabmcpCatalog) S.labmcp.registerCatalog(root.RhylthymeLabmcpCatalog);
}(typeof self !== 'undefined' ? self : this));
`;

const catalogOut = `/*! @rhylthyme/timeline ${version} | browser/labmcp-catalog.js | Apache-2.0
 * The LabMCP instrument catalogue for browser/schedule.js: with this script
 * on the page (before or after schedule.js), validateProgram checks LabMCP
 * instrument steps. Sets window.RhylthymeLabmcpCatalog. Generated by
 * tools/build-browser.js from ${CATALOG}.
 */
(function (root) {
  'use strict';
  var catalog = root.RhylthymeLabmcpCatalog = ${JSON.stringify(JSON.parse(fs.readFileSync(path.join(ROOT, CATALOG), 'utf8')))};
  if (root.RhylthymeSchedule) root.RhylthymeSchedule.labmcp.registerCatalog(catalog);
}(typeof self !== 'undefined' ? self : this));
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out);
fs.writeFileSync(CATALOG_OUT, catalogOut);
if (require.main === module) {
  console.log(`browser/schedule.js: ${modules.size} modules, ${(out.length / 1024).toFixed(0)} KB`);
  console.log(`browser/labmcp-catalog.js: ${(catalogOut.length / 1024).toFixed(0)} KB`);
}
